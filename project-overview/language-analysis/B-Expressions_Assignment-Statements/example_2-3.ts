let score: number = 80;

console.log(score == 80);   // true -  equal to
console.log(score != 100);  // true -  not equal to
console.log(score > 75);    // true -  greater than
console.log(score < 75);    // false - less than
console.log(score >= 80);   // true -  greater than or equal to
console.log(score <= 79);   // false - less than or equal to